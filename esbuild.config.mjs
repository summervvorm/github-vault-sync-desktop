import esbuild from 'esbuild';
import process from 'node:process';

const banner = `/*
This file is generated by esbuild. Do not edit directly.
Source: https://github.com/summervvorm/github-vault-sync
*/`;

const isTest = process.argv.includes('--test');
const isWatch = process.argv.includes('--watch');

/**
 * Obsidian 运行时自带这些模块，绝不能打进 bundle。
 * platform:'node' 会让 esbuild 自动把 node 内置模块视为 external。
 */
const pluginExternals = ['obsidian', 'electron', '@codemirror/*', '@lezer/*'];

/** @type {import('esbuild').BuildOptions} */
const pluginBuild = {
  entryPoints: ['src/main.ts'],
  outfile: 'main.js',
  bundle: true,
  format: 'cjs',
  platform: 'node',
  target: 'es2018',
  external: pluginExternals,
  banner: { js: banner },
  logLevel: 'info',
  treeShaking: true,
  sourcemap: false,
};

/**
 * 验收测试入口。
 * 测试只依赖 src/core（不含任何 obsidian import），
 * 因此可以原样打包后在纯 Node 下运行。
 */
const testBuild = {
  entryPoints: ['test/headless.ts'],
  outfile: 'test/headless.cjs',
  bundle: true,
  format: 'cjs',
  platform: 'node',
  target: 'node20',
  logLevel: 'info',
  sourcemap: false,
};

/** 无头 CLI：复用同一套 core，用于对真实 Vault 做初始化/同步/建仓库 */
const cliBuild = {
  entryPoints: ['scripts/vault-cli.ts'],
  outfile: 'scripts/vault-cli.cjs',
  bundle: true,
  format: 'cjs',
  platform: 'node',
  target: 'node20',
  logLevel: 'info',
  sourcemap: false,
};

/**
 * 插件级测试：把 obsidian 换成**功能性**桩，真实执行 onload / runSync / onunload。
 */
const pluginTestBuild = {
  entryPoints: ['test/plugin-e2e.ts'],
  outfile: 'test/plugin-e2e.cjs',
  bundle: true,
  format: 'cjs',
  platform: 'node',
  target: 'node20',
  alias: { obsidian: './test/stubs/obsidian-functional.ts' },
  logLevel: 'info',
  sourcemap: false,
};

if (isWatch) {
  const ctx = await esbuild.context(pluginBuild);
  await ctx.watch();
  console.log('[esbuild] watching...');
} else {
  await esbuild.build(pluginBuild);
  await esbuild.build(cliBuild);
  if (isTest) {
    await esbuild.build(testBuild);
    await esbuild.build(pluginTestBuild);
  }
}
